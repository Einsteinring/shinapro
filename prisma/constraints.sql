-- Защита от двойной брони на уровне базы.
--
-- В приложении слот проверяется внутри транзакции, но на Postgres этого мало:
-- при READ COMMITTED две одновременные транзакции обе прочитают «свободно»
-- и обе вставят строку. Уникальный индекс закрывает это окно физически,
-- а приложение превращает отказ базы в понятный ответ 409.
--
-- Индекс частичный по двум причинам:
--   status <> 'cancelled' — отменённая заявка слот не держит, время снова свободно;
--   time IS NULL          — визит без получасового слота (сдача шин на хранение),
--                           таких в один день может быть сколько угодно. NULL-значения
--                           уникальный индекс считает различными и в SQLite, и в Postgres.
--
-- Файл идемпотентный: выполняется после каждого prisma db push, который
-- о неизвестных ему индексах не знает и может их снести.

CREATE UNIQUE INDEX IF NOT EXISTS "Booking_slot_unique"
  ON "Booking" ("branchId", "date", "time")
  WHERE "status" <> 'cancelled';
